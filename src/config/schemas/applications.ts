/** A status staff can move a response to when the form uses custom review. */
export const zFormStatus = z.strictObject({
  id: z
    .string()
    .regex(/^[a-z0-9_]{1,24}$/)
    .refine((id) => !(RESERVED_STATUS_IDS as readonly string[]).includes(id), "That status id is reserved.")
    .describe("Stable status id, lowercase letters, numbers and underscores."),
  label: z.string().min(1).max(40).describe("Shown to staff and, in DMs, to the member."),
  tone: z.enum(["neutral", "note", "ok", "caution", "danger"]).default("neutral").describe("Colour of the status."),
  closes: z.boolean().default(false).describe("Counts as a final outcome (the response is no longer open)."),
  add_roles: roleList("Roles given when a response gets this status."),
  remove_roles: roleList("Roles taken away when a response gets this status."),
  dm_message: z.string().max(2000).default("").describe("DM sent when a response gets this status. Empty sends nothing."),
});
export type FormStatusDef = z.infer<typeof zFormStatus>;

