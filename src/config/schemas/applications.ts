/** Four modal pages of five questions each. Longer forms are asked page by page. */
export const MAX_APPLICATION_QUESTIONS = 20;
export const MAX_APPLICATION_OPENINGS = 25;
export const MAX_FORM_STATUSES = 8;

/** What sort of form an opening is. Templates on the dashboard prefill each one; every setting stays editable. */
export const FORM_KINDS = ["application", "rsvp", "questionnaire", "poll", "feedback", "report", "signup", "custom"] as const;
export type FormKind = (typeof FORM_KINDS)[number];

/**
 * - approve_deny: the classic application flow (pending, then accepted or denied).
 * - none: responses are simply recorded ("submitted"), nobody has to act on them.
 * - custom: staff move each response between statuses the server defines.
 */
export const FORM_REVIEW_MODES = ["approve_deny", "none", "custom"] as const;
export type FormReviewMode = (typeof FORM_REVIEW_MODES)[number];

/** Built-in statuses. Custom review adds the server's own status ids on top. */
export const APPLICATION_STATUSES = ["pending", "accepted", "denied"] as const;
export type ApplicationStatus = (typeof APPLICATION_STATUSES)[number];
export const SUBMITTED_STATUS = "submitted";
/** Any status a response can have: a built-in one, "submitted", or a custom status id. */
export type FormStatus = string;
export const RESERVED_STATUS_IDS = [...APPLICATION_STATUSES, SUBMITTED_STATUS] as const;

export const RSVP_CHOICES = ["going", "maybe", "not_going"] as const;
export type RsvpChoice = (typeof RSVP_CHOICES)[number];

/**
 * Question types: every ticket question type, plus ones built from them for forms. Number,
 * date and time are validated text inputs; yes/no and rating render as choices.
 */
export const FORM_QUESTION_TYPES = [...TICKET_QUESTION_TYPES, "number", "date", "time", "datetime", "yes_no", "rating"] as const;
export type FormQuestionType = (typeof FORM_QUESTION_TYPES)[number];

/** Extra checks on text answers. Regex uses `pattern`. */
export const FORM_TEXT_VALIDATIONS = ["none", "email", "url", "phone", "integer", "regex"] as const;
export type FormTextValidation = (typeof FORM_TEXT_VALIDATIONS)[number];

export const FORM_CONDITION_OPS = ["equals", "not_equals", "contains", "answered", "not_answered"] as const;
export type FormConditionOp = (typeof FORM_CONDITION_OPS)[number];

/**
 * A choice. Like a ticket question option, but a blank one (mid-edit on the dashboard) is kept
 * rather than failing the whole form; blank options are simply left out of the form in Discord.
 */
export const zFormOption = z.strictObject({
  label: z.string().max(100).default("").describe("Shown to the member."),
  value: z.string().max(100).default("").describe("Stored in the answer. Defaults to the label."),
  description: z.string().max(100).optional(),
});

export const zFormCondition = z.strictObject({
  question_id: z.string().max(64).describe("The earlier question this one depends on."),
  op: z.enum(FORM_CONDITION_OPS).default("equals").describe("How the earlier answer is compared."),
  value: z.string().max(100).default("").describe("Compared with the earlier answer (an option value or text). Ignored for answered / not answered."),
});
export type FormCondition = z.infer<typeof zFormCondition>;

/**
 * One form question. A superset of the ticket question shape, so every question saved before
 * Forms existed parses unchanged.
 */
export const zFormQuestion = z
  .strictObject({
    id: z.string().uuid().describe("Stable question ID. Generated by the dashboard, do not edit by hand."),
    label: z.string().max(45).default("").describe("Question label (Discord limit: 45 characters)."),
    type: z.enum(FORM_QUESTION_TYPES).default("text").describe("Question type. Defaults to \"text\"."),
    style: z.enum(["short", "paragraph"]).default("short").describe("Short is one line, paragraph is a multi-line box. Text only."),
    required: z.boolean().default(true).describe("Members must answer this question."),
    placeholder: z.string().max(100).default("").describe("Placeholder text shown in an empty text field."),
    help: z.string().max(100).default("").describe("Help text shown under the question label."),
    min_length: z.number().int().min(0).max(4000).default(0).describe("Minimum answer length (0 = no minimum). Text only."),
    max_length: z.number().int().min(1).max(4000).default(1000).describe("Maximum answer length. Text only."),
    content: z.string().max(4000).optional().describe("Markdown shown to the member. text_display only, which has no answer."),
    options: z.array(zFormOption).max(25).optional().describe("Choices for select, radio and checkbox questions."),
    min_values: z.number().int().min(0).max(25).optional().describe("Minimum selections (or files)."),
    max_values: z.number().int().min(1).max(25).optional().describe("Maximum selections (or files)."),
    validation: z.enum(FORM_TEXT_VALIDATIONS).default("none").describe("Extra check on text answers."),
    pattern: z.string().max(200).default("").describe("Regular expression a text answer must match, when validation is regex."),
    pattern_message: z.string().max(100).default("").describe("Shown when an answer doesn't match the pattern."),
    min_value: z.number().optional().describe("Lowest number allowed. Number questions only."),
    max_value: z.number().optional().describe("Highest number allowed. Number questions only."),
    scale: z.union([z.literal(5), z.literal(10)]).default(5).describe("Rating scale: 1 to 5 or 1 to 10."),
    show_if: zFormCondition.optional().describe("Only ask this question when an earlier answer matches."),
    page_break: z.boolean().default(false).describe("Start a new page of the form at this question."),
  })
  .superRefine((question, ctx) => {
    if (!question.label.trim()) {
      ctx.addIssue({ code: "custom", message: "Give this question a label.", path: ["label"] });
    }
    if (
      (question.type === "string_select" || question.type === "radio_group" || question.type === "checkbox_group") &&
      !question.options?.some((o) => o.label.trim())
    ) {
      ctx.addIssue({ code: "custom", message: "Add at least one option.", path: ["options"] });
    }
    if (question.type === "text_display" && !question.content?.trim()) {
      ctx.addIssue({ code: "custom", message: "Give this text block some content.", path: ["content"] });
    }
    if (question.min_length > question.max_length) {
      ctx.addIssue({ code: "custom", message: "Minimum length cannot be longer than the maximum.", path: ["min_length"] });
    }
    if (question.min_values !== undefined && question.max_values !== undefined && question.min_values > question.max_values) {
      ctx.addIssue({ code: "custom", message: "Minimum cannot be greater than maximum.", path: ["min_values"] });
    }
    if (question.min_value !== undefined && question.max_value !== undefined && question.min_value > question.max_value) {
      ctx.addIssue({ code: "custom", message: "The lowest number cannot be above the highest.", path: ["min_value"] });
    }
  });
export type FormQuestion = z.infer<typeof zFormQuestion>;

