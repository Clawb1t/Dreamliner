import { boolPerm, channelId } from "../schemaHelp.js";
import { zPluginSection } from "./pluginSection.js";
import { zTicketFormQuestion, type TicketFormQuestion } from "./tickets.js";

/**
 * Appeals: members (or banned users) ask for an infraction to be reviewed from the website
 * (/server/<id>/appeals). Staff decide from a Discord review channel or the dashboard's View
 * Appeals page; approving can lift the punishment.
 */

/** Dreamliner's own app emojis (see app-emojis.txt): they render in every server and in DMs. */
export const APPEAL_EMOJIS = {
  appeal: "<:icons_rules:1544417580565921832>",
  pending: "<:icons_hoursglass:1544417711864549479>",
  approved: "<:icons_Correct:1544417199798886530>",
  denied: "<:icons_Wrong:1544417460638457937>",
  needsInfo: "<:icons_question:1544417575864107078>",
  submitted: "<:icons_envelope:1544417793007681566>",
  note: "<:icons_pen:1544417369709871224>",
  lifted: "<:icons_unlock:1544417749617610852>",
} as const;

export const APPEAL_STATUSES = ["pending", "needs_info", "approved", "denied", "withdrawn"] as const;
export type AppealStatus = (typeof APPEAL_STATUSES)[number];

/** Infraction types that can be appealed. Notes, unbans, unmutes and cleans never can. */
export const APPEALABLE_TYPES = ["ban", "tempban", "softban", "kick", "mute", "tempmute", "warn"] as const;
export type AppealableType = (typeof APPEALABLE_TYPES)[number];

/** Question types appeal forms can use: everything the website can render as a plain form field.
 *  Discord-only pickers (users, roles, channels) and file uploads aren't offered. */
export const APPEAL_QUESTION_TYPES = [
  "text",
  "string_select",
  "radio_group",
  "checkbox_group",
  "checkbox",
  "text_display",
] as const;

export const MAX_APPEAL_FORMS = 10;
export const MAX_APPEAL_QUESTIONS = 20;

/** The built-in form's id. Fixed (not random) so defaults stay stable between config loads. */
export const DEFAULT_APPEAL_FORM_ID = "00000000-0000-4000-8000-0000000a9fe1";

/** "30m", "24h", "7d", "2w", or "" for none. */
const duration = (description: string, fallback: string) =>
  z
    .string()
    .regex(/^(\d+[smhdw])?$/i, 'Use a number and unit like "24h", "7d" or "2w", or leave empty.')
    .default(fallback)
    .describe(description);

const colorInt = (description: string, fallback: number) =>
  z.number().int().min(0).max(0xffffff).default(fallback).describe(description);

const zAppealQuestion = zTicketFormQuestion.superRefine((question, ctx) => {
  if (!(APPEAL_QUESTION_TYPES as readonly string[]).includes(question.type)) {
    ctx.addIssue({
      code: "custom",
      message: "Appeal forms are filled in on the website, so they can use text, choices, checkboxes and text blocks.",
      path: ["type"],
    });
  }
});

