export const zAppealForm = z.strictObject({
  id: z.string().uuid().describe("Stable form ID. Generated by the dashboard, do not edit by hand."),
  name: z.string().max(80).default("Appeal form").describe("Shown on the dashboard and to reviewers."),
  intro: z.string().max(2000).default("").describe("Optional text shown above the questions."),
  questions: z
    .array(zAppealQuestion)
    .max(MAX_APPEAL_QUESTIONS)
    .default([])
    .describe(`Up to ${MAX_APPEAL_QUESTIONS} questions.`),
});

export const zAppealTypeRule = z.strictObject({
  enabled: z.boolean().default(true).describe("Whether this kind of infraction can be appealed."),
  form_id: z.string().max(64).default("").describe("Which appeal form to use. Empty uses the first form."),
  min_wait: duration("How long after the infraction before it can be appealed, e.g. 24h. Empty for straight away.", ""),
  window: duration("How long the infraction stays appealable, e.g. 90d. Empty for forever.", ""),
  allow_inactive: z
    .boolean()
    .default(false)
    .describe("Allow appeals against infractions that have expired or already been lifted."),
  auto_reverse: z
    .boolean()
    .default(true)
    .describe("When an appeal is approved, lift the punishment: unban, remove the timeout, or revoke the case."),
});

const typeRule = (enabled: boolean) => zAppealTypeRule.default({ enabled });

